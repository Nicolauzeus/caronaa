import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import postgres from "postgres";

const migration = (name) =>
  readFileSync(new URL(`../drizzle/migrations/${name}.sql`, import.meta.url), "utf8");
const functionsFrom = (source, marker) => {
  const index = source.indexOf(marker);
  if (index < 0) throw new Error(`Migration section missing: ${marker}`);
  return source
    .slice(index)
    .replaceAll("CREATE FUNCTION public.", "CREATE OR REPLACE FUNCTION public.");
};
const conditional = (name, condition, first, existing = "") => `
DO $repair_${name}$ BEGIN
  IF ${condition} THEN
    EXECUTE $sql_${name}$${first}$sql_${name}$;
  ${existing ? `ELSE EXECUTE $existing_${name}$${existing}$existing_${name}$;` : ""}
  END IF;
END $repair_${name}$;`;

// Assemble canonical migrations instead of maintaining reduced parallel RPC implementations.
export function buildRideRpcRepair() {
  const admin = migration("0025_admin_operation_pages");
  const routines = migration("0028_weekly_ride_routines");
  const routineColumns = ["ride_offers", "ride_requests"]
    .map(
      (table) => `
ALTER TABLE public.${table}
  ADD COLUMN IF NOT EXISTS routine_id uuid REFERENCES public.ride_routines(routine_id),
  ADD COLUMN IF NOT EXISTS routine_date date,
  ADD COLUMN IF NOT EXISTS routine_override boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS routine_suppressed boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS ${table}_routine_slot ON public.${table}(routine_id,routine_date);
CREATE UNIQUE INDEX IF NOT EXISTS ${table}_routine_departure_idx ON public.${table}(routine_id,ride_date,departure_time) WHERE routine_id IS NOT NULL AND status <> 'cancelled';`,
    )
    .join("\n");
  return [
    "-- Generated by scripts/repair-ride-rpcs.mjs. Requires application base migrations 0000-0022.\nBEGIN;\nSET LOCAL lock_timeout = '10s';\nSELECT pg_advisory_xact_lock(74120391);",
    migration("0023_flexible_time_tolerance_matching"),
    migration("0024_geographic_ride_matching"),
    conditional(
      "admin",
      "to_regclass('public.admin_driver_reviews') IS NULL",
      admin,
      functionsFrom(admin, "CREATE FUNCTION public.get_admin_operation_data"),
    ),
    "ALTER TABLE public.admin_driver_reviews ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON public.admin_driver_reviews FROM PUBLIC,anon,authenticated;",
    conditional(
      "safety",
      "to_regclass('public.ride_boarding_codes') IS NULL",
      migration("0026_ride_operational_safety"),
    ),
    migration("0027_automatic_ride_cost_splitting"),
    conditional(
      "routines",
      "to_regclass('public.ride_routines') IS NULL",
      routines,
      routineColumns +
        "\n" +
        functionsFrom(routines, "CREATE FUNCTION public.materialize_ride_routine"),
    ),
    "ALTER TABLE public.ride_routines ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON public.ride_routines FROM PUBLIC,anon,authenticated;\nGRANT ALL ON public.ride_routines TO service_role;",
    migration("0029_secure_ride_cost_updates"),
    migration("0030_directional_geographic_matching"),
    migration("0032_canonical_ride_creation_rpcs"),
    "COMMIT;\n",
  ].join("\n\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sql = buildRideRpcRepair();
  if (process.argv.includes("--apply")) {
    const url = process.env.LOVABLE_DB_MIGRATION_URL;
    if (!url)
      throw new Error(
        "Configure LOVABLE_DB_MIGRATION_URL com uma conexao administrativa. A chave publica nao permite DDL.",
      );
    const db = postgres(url, { max: 1, connect_timeout: 10 });
    try {
      await db.unsafe(sql).simple();
      console.log("RPCs e estruturas reparadas; recarga do schema cache solicitada.");
    } finally {
      await db.end({ timeout: 5 });
    }
  } else {
    const output = process.argv[2] ?? "/tmp/caronaa-ride-rpc-repair.sql";
    writeFileSync(output, sql);
    console.log(`SQL unificado gerado em ${output}`);
  }
}
