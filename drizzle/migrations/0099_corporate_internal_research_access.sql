-- 0099: employee-verified internal corporate research. Dependencies: 0095,0096,0097,0098.
-- No automatic employee enrollment, no public rides created; apply after backup and tests.

-- Explicit HR/admin verification is bound to the authenticated user AND this form.
-- No domain-only enrollment; survey badge never conveys employment.
CREATE TABLE IF NOT EXISTS public.corporate_research_memberships (
 form_id uuid NOT NULL REFERENCES public.research_forms(id) ON DELETE RESTRICT,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 verified_by uuid NOT NULL REFERENCES auth.users(id),
 verification_reference text NOT NULL CHECK (length(btrim(verification_reference)) BETWEEN 8 AND 180),
 verified_at timestamptz NOT NULL DEFAULT now(),
 revoked_at timestamptz,
 PRIMARY KEY(form_id,user_id)
);
CREATE INDEX IF NOT EXISTS corporate_research_member_user_idx ON public.corporate_research_memberships(user_id,form_id)
 WHERE revoked_at IS NULL;
CREATE TABLE IF NOT EXISTS public.corporate_research_answer_owners (
 answer_id uuid PRIMARY KEY REFERENCES public.research_answers(id) ON DELETE RESTRICT,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.corporate_research_access_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 form_id uuid NOT NULL REFERENCES public.research_forms(id) ON DELETE RESTRICT,
 user_id uuid NOT NULL REFERENCES auth.users(id),
 action text NOT NULL CHECK(action IN ('GRANTED','REVOKED')),
 operator_id uuid NOT NULL REFERENCES auth.users(id),
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.corporate_research_memberships ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corporate_research_answer_owners ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.corporate_research_access_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.corporate_research_memberships,public.corporate_research_answer_owners,public.corporate_research_access_audit FROM PUBLIC,anon,authenticated;
