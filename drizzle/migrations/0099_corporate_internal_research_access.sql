CREATE OR REPLACE FUNCTION public.is_restricted_research(p_form_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT EXISTS(
  SELECT 1 FROM public.research_configurations c WHERE c.form_id=p_form_id
  AND (c.settings->>'accessPolicy' IN ('COLABORADORES_DA_EMPRESA','MEMBROS_DA_INSTITUICAO')
   OR c.settings->>'templateKey'='EMPRESA_CARONA_INTERNA')
 );
$$;
REVOKE ALL ON FUNCTION public.is_restricted_research(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_restricted_research(uuid) TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.can_access_restricted_research(p_form_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT NOT public.is_restricted_research(p_form_id) OR
  EXISTS(
   SELECT 1 FROM public.corporate_research_memberships m
   JOIN auth.users u ON u.id=m.user_id
   WHERE m.form_id=p_form_id AND m.user_id=auth.uid()
    AND m.revoked_at IS NULL AND u.email_confirmed_at IS NOT NULL
  );
$$;
REVOKE ALL ON FUNCTION public.can_access_restricted_research(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_access_restricted_research(uuid) TO anon,authenticated;

-- Restrictive policies ADD to every existing permissive SELECT policy (including
-- anonymous published, admin and service flows); admin may manage all forms.
-- RPC submissions require verified MEMBERSHIP, even for CARONAA administrators.
CREATE POLICY research_restricted_forms_guard ON public.research_forms AS RESTRICTIVE
 FOR SELECT TO anon,authenticated USING(
  public.has_role(auth.uid(),'admin') OR public.can_access_restricted_research(id));
CREATE POLICY research_restricted_versions_guard ON public.research_form_versions AS RESTRICTIVE
 FOR SELECT TO anon,authenticated USING(
  public.has_role(auth.uid(),'admin') OR public.can_access_restricted_research(form_id));

-- The policy must not query the ownership table as the browser role:
-- direct SELECT on that table is deliberately REVOKED for all browser users.
CREATE OR REPLACE FUNCTION public.owns_corporate_research_answer(p_answer_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $
 SELECT EXISTS (
   SELECT 1 FROM public.corporate_research_answer_owners o
   WHERE o.answer_id=p_answer_id AND o.user_id=auth.uid()
 );
$;
REVOKE ALL ON FUNCTION public.owns_corporate_research_answer(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.owns_corporate_research_answer(uuid) TO authenticated;

-- Protect raw response data as well as forms/versions. A public-answer INSERT policy
-- from older migrations must not permit crafted inserts for corporate forms.
CREATE POLICY research_restricted_answer_read_guard ON public.research_answers AS RESTRICTIVE
 FOR SELECT TO anon,authenticated
 USING (
  NOT public.is_restricted_research(form_id)
  OR public.has_role(auth.uid(),'admin')
  OR (
    public.can_access_restricted_research(form_id)
    AND public.owns_corporate_research_answer(id)
  )
 );
CREATE POLICY research_restricted_answer_insert_guard ON public.research_answers AS RESTRICTIVE
 FOR INSERT TO anon,authenticated
 WITH CHECK(NOT public.is_restricted_research(form_id));
CREATE POLICY research_restricted_answer_update_guard ON public.research_answers AS RESTRICTIVE
 FOR UPDATE TO anon,authenticated
 USING(NOT public.is_restricted_research(form_id))
 WITH CHECK(NOT public.is_restricted_research(form_id));
CREATE POLICY research_restricted_answer_delete_guard ON public.research_answers AS RESTRICTIVE
 FOR DELETE TO anon,authenticated
 USING(NOT public.is_restricted_research(form_id));

CREATE OR REPLACE FUNCTION public.grant_corporate_research_access(
 p_form_id uuid,p_user_id uuid,p_reference text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(),'admin') THEN
   RAISE EXCEPTION 'Apenas administradores podem validar o vínculo' USING ERRCODE='42501'; END IF;
 IF NOT public.is_restricted_research(p_form_id)
    OR length(btrim(coalesce(p_reference,''))) NOT BETWEEN 8 AND 180
    OR NOT EXISTS(SELECT 1 FROM auth.users u WHERE u.id=p_user_id AND u.email_confirmed_at IS NOT NULL)
 THEN RAISE EXCEPTION 'Confirme a pesquisa restrita, a conta e a referência de verificação' USING ERRCODE='42501'; END IF;
 INSERT INTO public.corporate_research_memberships(form_id,user_id,verified_by,verification_reference,verified_at,revoked_at)
 VALUES(p_form_id,p_user_id,auth.uid(),btrim(p_reference),now(),null)
 ON CONFLICT(form_id,user_id) DO UPDATE SET verified_by=excluded.verified_by,
 verification_reference=excluded.verification_reference,verified_at=now(),revoked_at=null;
 INSERT INTO public.corporate_research_access_audit(form_id,user_id,operator_id,action)
 VALUES(p_form_id,p_user_id,auth.uid(),'GRANTED');
 RETURN true;
END $$;
REVOKE ALL ON FUNCTION public.grant_corporate_research_access(uuid,uuid,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.grant_corporate_research_access(uuid,uuid,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.revoke_corporate_research_access(p_form_id uuid,p_user_id uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(),'admin')
 THEN RAISE EXCEPTION 'Apenas administradores podem revogar o vínculo' USING ERRCODE='42501'; END IF;
 UPDATE public.corporate_research_memberships SET revoked_at=now()
 WHERE form_id=p_form_id AND user_id=p_user_id AND revoked_at IS NULL;
 IF NOT FOUND THEN RETURN false; END IF;
 INSERT INTO public.corporate_research_access_audit(form_id,user_id,operator_id,action)
 VALUES(p_form_id,p_user_id,auth.uid(),'REVOKED');
 RETURN true;
END $$;
REVOKE ALL ON FUNCTION public.revoke_corporate_research_access(uuid,uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.revoke_corporate_research_access(uuid,uuid) TO authenticated;

-- Admin-controlled roster review. No verification references are returned to the UI.
CREATE OR REPLACE FUNCTION public.list_corporate_research_access(p_form_id uuid)
RETURNS TABLE(user_id uuid,verified_at timestamptz,revoked_at timestamptz)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(),'admin')
 THEN RAISE EXCEPTION 'Acesso restrito a administradores' USING ERRCODE='42501'; END IF;
 RETURN QUERY SELECT m.user_id,m.verified_at,m.revoked_at
 FROM public.corporate_research_memberships m WHERE m.form_id=p_form_id
 ORDER BY m.verified_at DESC LIMIT 500;
END $$;
REVOKE ALL ON FUNCTION public.list_corporate_research_access(uuid) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.list_corporate_research_access(uuid) TO authenticated;

-- Prevent crafted journeys from creating a DRIVER interest without matching evidence.
CREATE OR REPLACE FUNCTION public.assert_corporate_research_driver(
 p_form_id uuid,p_version_id uuid,p_answers jsonb,p_journey jsonb)
RETURNS void LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
DECLARE drives_id text;seats_id text;offer_id text;
BEGIN
 IF NOT public.is_restricted_research(p_form_id) THEN RETURN; END IF;
 -- Generic restricted forms may be non-corporate; the explicit corporate template
 -- is the only one for which these answer semantics are mandatory.
 IF NOT EXISTS (SELECT 1 FROM public.research_configurations c
   WHERE c.form_id=p_form_id AND c.settings->>'templateKey'='EMPRESA_CARONA_INTERNA')
 THEN RETURN; END IF;
 IF p_journey->>'profile' NOT IN ('MOTORISTA','AMBOS') THEN RETURN; END IF;
 SELECT max(q.value->>'id') FILTER(WHERE q.value->>'semanticCode'='CORP_DRIVES_CAR'),
        max(q.value->>'id') FILTER(WHERE q.value->>'semanticCode'='SEATS_AVAILABLE'),
        max(q.value->>'id') FILTER(WHERE q.value->>'semanticCode'='RIDE_OFFER_INTENT')
 INTO drives_id,seats_id,offer_id
 FROM public.research_form_versions v
 CROSS JOIN LATERAL jsonb_array_elements(v.schema_json->'sections') ss
 CROSS JOIN LATERAL jsonb_array_elements(ss.value->'questions') q
 WHERE v.id=p_version_id AND v.form_id=p_form_id;
 IF drives_id IS NULL OR seats_id IS NULL OR offer_id IS NULL
   OR p_answers->>drives_id<>'SIM' OR p_answers->>offer_id<>'SIM'
   OR coalesce(p_answers->>seats_id,'') !~ '^[1-4]$'
 THEN RAISE EXCEPTION 'Perfil motorista exige carro, lugar livre e interesse confirmado' USING ERRCODE='42501';
 END IF;
END $$;
REVOKE ALL ON FUNCTION public.assert_corporate_research_driver(uuid,uuid,jsonb,jsonb) FROM PUBLIC,anon,authenticated;

-- Extend latest configuration validator from 0098 without invalidating previous models.
CREATE OR REPLACE FUNCTION public.validate_research_configuration(p jsonb)
RETURNS void LANGUAGE plpgsql SET search_path=public AS $$
DECLARE k text; item jsonb; t text; schedule jsonb;
BEGIN
 IF jsonb_typeof(p) IS DISTINCT FROM 'object' OR pg_column_size(p)>16384 OR p->>'schemaVersion' IS DISTINCT FROM '1' THEN
  RAISE EXCEPTION 'Configuração inválida'; END IF;
 FOR k IN SELECT jsonb_object_keys(p) LOOP
  IF k NOT IN ('schemaVersion','templateKey','institutionId','institutionName','publicName','campus','nearbyUniversity','region','address','latitude','longitude','campaignName','campaignType','acquisitionSource','launchDate','timezone','serviceState','days','outboundTimes','returnTimes','flexibilityMinutes','profiles','modes','usagePolicy','priceReference','institutionalContact','partnershipDescription','partnershipConfirmed','safeMeetingPoints','profileSchedules','accessPolicy','pricing') THEN RAISE EXCEPTION 'Campo de configuração não reconhecido'; END IF;
 END LOOP;
 FOR k IN SELECT unnest(ARRAY['campus','address','campaignName','acquisitionSource','priceReference','institutionalContact','partnershipDescription']) LOOP
  IF jsonb_typeof(p->k) IS DISTINCT FROM 'string' OR length(p->>k)>1500 THEN RAISE EXCEPTION 'Texto de configuração inválido'; END IF;
 END LOOP;
 IF p ? 'nearbyUniversity' THEN
  IF jsonb_typeof(p->'nearbyUniversity') IS DISTINCT FROM 'string'
    OR length(p->>'nearbyUniversity')>180
  THEN RAISE EXCEPTION 'Instituição de ensino próxima inválida'; END IF;
 END IF;
 IF p->>'templateKey'='EMPRESA_CARONA_CAMPUS' THEN
  IF length(btrim(coalesce(p->>'nearbyUniversity',''))) NOT BETWEEN 2 AND 180
    OR length(btrim(coalesce(p->>'campus','')))<2
    OR length(btrim(coalesce(p->>'address','')))<5
  THEN RAISE EXCEPTION 'Informe a empresa, a unidade, o endereço e a universidade próxima'; END IF;
 END IF;
 IF p->>'templateKey' = 'EMPRESA_CARONA_INTERNA' THEN
    IF p->>'accessPolicy' IS DISTINCT FROM 'COLABORADORES_DA_EMPRESA'
       OR p->'modes' IS DISTINCT FROM '["CARONA"]'::jsonb
       OR length(btrim(coalesce(p->>'campus',''))) < 2
       OR length(btrim(coalesce(p->>'address',''))) < 5
    THEN RAISE EXCEPTION 'Pesquisa corporativa exige restrição de colaboradores, unidade e carona compartilhada'; END IF;
 END IF;
 FOR k IN SELECT unnest(ARRAY['templateKey','institutionId','institutionName','publicName','region','timezone','usagePolicy']) LOOP
  IF jsonb_typeof(p->k) IS DISTINCT FROM 'string' OR length(btrim(p->>k)) NOT BETWEEN 2 AND 1500 THEN RAISE EXCEPTION 'Confira o campo %',k; END IF;
 END LOOP;
 IF p->>'institutionId' !~ '^[A-Z0-9_-]{2,80}$'
  OR p->>'serviceState' NOT IN ('PLANEJADO','CONFIRMADO','EM_OPERACAO','ADIADO')
  OR p->>'serviceState' IS NULL
  OR p->>'campaignType' NOT IN ('INSTITUCIONAL','EVENTO','ORGANICO','OUTRO') OR p->>'campaignType' IS NULL
  OR NOT EXISTS(SELECT 1 FROM pg_timezone_names WHERE name=p->>'timezone')
 THEN RAISE EXCEPTION 'Identificação, campanha, situação ou fuso inválido'; END IF;
 IF p->>'launchDate' IS NOT NULL THEN
  IF p->>'launchDate' !~ '^\d{4}-\d{2}-\d{2}$' OR to_char((p->>'launchDate')::date,'YYYY-MM-DD')<>p->>'launchDate'
   THEN RAISE EXCEPTION 'Data inválida'; END IF;
 END IF;
 IF (p->>'latitude' IS NULL)<>(p->>'longitude' IS NULL) THEN RAISE EXCEPTION 'Coordenadas incompletas'; END IF;
 IF p->>'latitude' IS NOT NULL AND ((p->>'latitude')::numeric NOT BETWEEN -90 AND 90 OR (p->>'longitude')::numeric NOT BETWEEN -180 AND 180) THEN RAISE EXCEPTION 'Coordenadas inválidas'; END IF;
 IF jsonb_typeof(p->'flexibilityMinutes') IS DISTINCT FROM 'number' OR (p->>'flexibilityMinutes') !~ '^\d+$' OR (p->>'flexibilityMinutes')::int NOT BETWEEN 0 AND 120 THEN RAISE EXCEPTION 'Flexibilidade inválida'; END IF;
 FOR k IN SELECT unnest(ARRAY['days','outboundTimes','returnTimes','profiles','modes','safeMeetingPoints']) LOOP
  IF jsonb_typeof(p->k) IS DISTINCT FROM 'array' OR jsonb_array_length(p->k)>48 THEN RAISE EXCEPTION 'Lista inválida: %',k; END IF;
  IF k NOT IN ('returnTimes','safeMeetingPoints') AND jsonb_array_length(p->k)=0 THEN RAISE EXCEPTION 'Lista vazia: %',k; END IF;
  IF (SELECT count(DISTINCT value) FROM jsonb_array_elements(p->k))<>jsonb_array_length(p->k) THEN RAISE EXCEPTION 'Itens repetidos: %',k; END IF;
  FOR item IN SELECT value FROM jsonb_array_elements(p->k) LOOP
   t:=item#>>'{}';
   IF k<>'days' AND jsonb_typeof(item) IS DISTINCT FROM 'string' THEN RAISE EXCEPTION 'Item inválido'; END IF;
   IF k='safeMeetingPoints' AND length(btrim(t)) NOT BETWEEN 2 AND 180 THEN RAISE EXCEPTION 'Ponto de embarque inválido'; END IF;
   IF k='days' AND (t !~ '^[1-7]$' OR jsonb_typeof(item)<>'number') THEN RAISE EXCEPTION 'Dia inválido'; END IF;
   IF k IN ('outboundTimes','returnTimes') AND t !~ '^([01]\d|2[0-3]):[0-5]\d$' THEN RAISE EXCEPTION 'Horário inválido'; END IF;
   IF k='profiles' AND t NOT IN ('PASSAGEIRO','MOTORISTA','AMBOS') THEN RAISE EXCEPTION 'Perfil inválido'; END IF;
   IF k='modes' AND t NOT IN ('CARONA','TRANSPORTE_PROFISSIONAL_INTERESSE') THEN RAISE EXCEPTION 'Modalidade inválida'; END IF;
  END LOOP;
 END LOOP;
 IF jsonb_typeof(p->'partnershipConfirmed') IS DISTINCT FROM 'boolean' THEN RAISE EXCEPTION 'Confirmação de parceria inválida'; END IF;
 IF coalesce(p->>'partnershipDescription','')<>'' AND p->>'partnershipConfirmed'<>'true' THEN RAISE EXCEPTION 'Parceria não confirmada'; END IF;
 IF p ? 'accessPolicy' AND coalesce(p->>'accessPolicy','') NOT IN ('PESQUISA_PUBLICA','MEMBROS_DA_INSTITUICAO','COLABORADORES_DA_EMPRESA') THEN RAISE EXCEPTION 'Política de público inválida'; END IF;
 IF p ? 'pricing' THEN
  IF jsonb_typeof(p->'pricing') IS DISTINCT FROM 'object' OR p#>>'{pricing,currency}' IS DISTINCT FROM 'BRL' THEN RAISE EXCEPTION 'Referência de preço inválida'; END IF;
  FOR k IN SELECT jsonb_object_keys(p->'pricing') LOOP IF k NOT IN ('currency','referencePerTrip','referenceSource') THEN RAISE EXCEPTION 'Campo de preço não reconhecido'; END IF; END LOOP;
  IF NOT(p->'pricing' ? 'referencePerTrip') OR jsonb_typeof(p#>'{pricing,referenceSource}') IS DISTINCT FROM 'string' OR length(p#>>'{pricing,referenceSource}')>500 THEN RAISE EXCEPTION 'Origem da referência inválida'; END IF;
  IF p#>>'{pricing,referencePerTrip}' IS NOT NULL AND (jsonb_typeof(p#>'{pricing,referencePerTrip}')<>'number' OR (p#>>'{pricing,referencePerTrip}')::numeric NOT BETWEEN 0 AND 10000 OR length(btrim(coalesce(p#>>'{pricing,referenceSource}','')))<3) THEN RAISE EXCEPTION 'Confira o valor e a origem da referência de preço'; END IF;
 END IF;
 IF p ? 'profileSchedules' THEN
  IF jsonb_typeof(p->'profileSchedules') IS DISTINCT FROM 'array' OR jsonb_array_length(p->'profileSchedules')>3 THEN RAISE EXCEPTION 'Horários por perfil inválidos'; END IF;
  IF (SELECT count(DISTINCT value->>'profile') FROM jsonb_array_elements(p->'profileSchedules'))<>jsonb_array_length(p->'profileSchedules') THEN RAISE EXCEPTION 'Perfis de horário repetidos'; END IF;
  FOR schedule IN SELECT value FROM jsonb_array_elements(p->'profileSchedules') LOOP
   IF NOT(p->'profiles' ? coalesce(schedule->>'profile','')) THEN RAISE EXCEPTION 'Perfil não habilitado'; END IF;
   PERFORM public.validate_research_configuration((p-'profileSchedules')||schedule-'profile');
  END LOOP;
 END IF;
END $$;


-- Public configuration must not disclose restricted corporate metadata.
CREATE OR REPLACE FUNCTION public.get_public_research_configuration(p_code text)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $$
 SELECT jsonb_build_object('revision',c.revision,'settings',c.settings-'institutionalContact')
 FROM public.research_configurations c JOIN public.research_forms f ON f.id=c.form_id
 WHERE lower(f.code)=lower(p_code) AND f.status='PUBLICADO' AND f.is_enabled
  AND public.can_access_restricted_research(f.id)
$$;

-- Transactional responses and interests must check membership and answer ownership.
CREATE OR REPLACE FUNCTION public.submit_configured_research_answer(p_form_id uuid,p_version_id uuid,p_submission_key uuid,p_answers jsonb,p_revision integer,p_journey jsonb,p_research_consent boolean)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE c public.research_configurations%ROWTYPE;a public.research_answers%ROWTYPE;j jsonb;existing public.research_journeys%ROWTYPE;
BEGIN
 IF p_research_consent IS DISTINCT FROM true OR p_submission_key IS NULL THEN RAISE EXCEPTION 'Consentimento obrigatório'; END IF;
 IF NOT public.can_access_restricted_research(p_form_id) THEN RAISE EXCEPTION 'Colaborador não autorizado' USING ERRCODE='42501'; END IF;
 -- Lock the form first, in the same order as configuration, publication and removal.
 PERFORM 1 FROM public.research_forms WHERE id=p_form_id FOR SHARE;
 PERFORM pg_advisory_xact_lock(hashtextextended(p_form_id::text||p_submission_key::text,0));
 SELECT * INTO a FROM public.research_answers WHERE form_id=p_form_id AND client_submission_key=p_submission_key;
 IF FOUND THEN
  SELECT * INTO existing FROM public.research_journeys WHERE answer_id=a.id;
  IF public.is_restricted_research(p_form_id) AND NOT EXISTS (
    SELECT 1 FROM public.corporate_research_answer_owners o
    WHERE o.answer_id=a.id AND o.user_id=auth.uid()
  ) THEN RAISE EXCEPTION 'Recibo pertence a outro colaborador' USING ERRCODE='42501'; END IF;
  IF NOT FOUND OR a.version_id<>p_version_id OR a.answers<>p_answers OR existing.configuration_revision<>p_revision
   OR existing.journey IS DISTINCT FROM public.validate_research_journey(p_journey,existing.configuration_snapshot)
  THEN RAISE EXCEPTION 'Recibo já utilizado para outra resposta' USING ERRCODE='23505'; END IF;
  RETURN true;
 END IF;
 SELECT * INTO c FROM public.research_configurations WHERE form_id=p_form_id FOR SHARE;
 IF NOT FOUND OR c.revision<>p_revision THEN RAISE EXCEPTION 'Configuração atualizada. Recarregue a pesquisa antes de enviar.' USING ERRCODE='40001'; END IF;
 j:=public.validate_research_journey(p_journey,c.settings);
 IF public.is_restricted_research(p_form_id)
 THEN PERFORM public.assert_corporate_research_driver(p_form_id,p_version_id,p_answers,j); END IF;
 -- Existing triggers enforce enabled publication, version ownership and all 16 question types.
 INSERT INTO public.research_answers(form_id,version_id,client_submission_key,answers,consent_accepted)
 VALUES(p_form_id,p_version_id,p_submission_key,p_answers,true) RETURNING * INTO a;
 INSERT INTO public.research_journeys(answer_id,configuration_revision,configuration_snapshot,journey)
 VALUES(a.id,c.revision,c.settings,j);
 IF public.is_restricted_research(p_form_id) THEN
    INSERT INTO public.corporate_research_answer_owners(answer_id,user_id)
    VALUES (a.id,auth.uid());
 END IF;
 RETURN true;
END $$;

CREATE OR REPLACE FUNCTION public.register_research_interest(p_form_id uuid,p_submission_key uuid,p_profile text,p_consent boolean,p_journey jsonb DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE a uuid;j jsonb;s text;c jsonb;candidate jsonb;previous jsonb;original_schedule jsonb;v_version uuid;v_answers jsonb;
BEGIN
 IF p_consent IS DISTINCT FROM true OR p_profile IS NULL OR p_profile NOT IN ('PASSAGEIRO','MOTORISTA') THEN RAISE EXCEPTION 'Confirme separadamente o interesse neste perfil'; END IF;
 IF NOT public.can_access_restricted_research(p_form_id) THEN RAISE EXCEPTION 'Colaborador não autorizado' USING ERRCODE='42501'; END IF;
 PERFORM 1 FROM public.research_forms WHERE id=p_form_id AND status='PUBLICADO' AND is_enabled FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Pesquisa indisponível para novos interesses' USING ERRCODE='42501'; END IF;
 SELECT ra.id,rj.journey,rj.configuration_snapshot INTO a,j,c FROM public.research_answers ra JOIN public.research_journeys rj ON rj.answer_id=ra.id
 WHERE ra.form_id=p_form_id AND ra.client_submission_key=p_submission_key AND ra.submitted_at>now()-interval '90 days' FOR UPDATE OF rj;
 IF NOT FOUND OR j->>'mode'<>'CARONA' OR j->>'profile' NOT IN (p_profile,'AMBOS') THEN RAISE EXCEPTION 'Recibo ou perfil indisponível' USING ERRCODE='42501'; END IF;
 IF public.is_restricted_research(p_form_id) THEN
   IF NOT EXISTS (SELECT 1 FROM public.corporate_research_answer_owners o WHERE o.answer_id=a AND o.user_id=auth.uid())
   THEN RAISE EXCEPTION 'Recibo não pertence a este colaborador' USING ERRCODE='42501'; END IF;
   SELECT ra.version_id,ra.answers INTO STRICT v_version,v_answers FROM public.research_answers ra WHERE ra.id=a;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(c->'profileSchedules') x WHERE x->>'profile'=p_profile) THEN
  SELECT x INTO original_schedule FROM jsonb_array_elements(c->'profileSchedules') x WHERE x->>'profile'=j->>'profile';
  IF original_schedule IS NOT NULL THEN
   c:=jsonb_set(c,'{profileSchedules}',(c->'profileSchedules')||jsonb_build_array(original_schedule||jsonb_build_object('profile',p_profile)));
  END IF;
 END IF;
 c:=jsonb_set(c,'{profiles}',jsonb_build_array(p_profile));
 candidate:=public.validate_research_journey(coalesce(p_journey,j)||jsonb_build_object('profile',p_profile,'marketingConsent',j->'marketingConsent','partnerSharingConsent',j->'partnerSharingConsent'),c);
 IF candidate->>'mode'<>'CARONA' THEN RAISE EXCEPTION 'Modalidade profissional não habilitada para carona' USING ERRCODE='42501'; END IF;
 IF public.is_restricted_research(p_form_id) THEN
   PERFORM public.assert_corporate_research_driver(p_form_id,v_version,v_answers,candidate);
 END IF;
 SELECT journey INTO previous FROM public.research_interest_requests WHERE answer_id=a AND profile=p_profile;
 IF FOUND AND previous IS DISTINCT FROM candidate THEN RAISE EXCEPTION 'Interesse já registrado com outro trajeto' USING ERRCODE='40001'; END IF;
 s:=CASE WHEN p_profile='MOTORISTA' THEN 'DISPONIBILIDADE_REGISTRADA' ELSE 'INTERESSE_REGISTRADO' END;
 INSERT INTO public.research_interest_requests(answer_id,profile,status,consent_accepted,journey) VALUES(a,p_profile,s,true,candidate) ON CONFLICT DO NOTHING;
 RETURN s;
END $$;

-- Participation receipts cannot be claimed by other verified employees.
CREATE OR REPLACE FUNCTION public.claim_research_participation(p_submission_key uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,auth AS $$
DECLARE v_auth auth.users%ROWTYPE;v_answer public.research_answers%ROWTYPE;v_claim public.research_participation_badges%ROWTYPE;
BEGIN
 SELECT * INTO v_auth FROM auth.users WHERE id=auth.uid();
 IF NOT FOUND THEN RAISE EXCEPTION 'Inicie sessão para registrar a participação' USING ERRCODE='42501'; END IF;
 IF v_auth.email_confirmed_at IS NULL THEN
   RAISE EXCEPTION 'Confirme seu e-mail antes de vincular a pesquisa à conta' USING ERRCODE='42501';
 END IF;
 SELECT * INTO v_answer FROM public.research_answers
  WHERE client_submission_key=p_submission_key
  ORDER BY submitted_at DESC LIMIT 1;
 IF NOT FOUND OR v_answer.submitted_at < now()-interval '90 days'
  THEN RAISE EXCEPTION 'Recibo de participação inválido ou expirado' USING ERRCODE='42501'; END IF;
 IF NOT public.can_access_restricted_research(v_answer.form_id)
 THEN RAISE EXCEPTION 'Colaborador não autorizado a vincular participação' USING ERRCODE='42501'; END IF;
 IF public.is_restricted_research(v_answer.form_id) AND NOT EXISTS (
  SELECT 1 FROM public.corporate_research_answer_owners o
  WHERE o.answer_id=v_answer.id AND o.user_id=auth.uid()
 ) THEN RAISE EXCEPTION 'Recibo corporativo pertence a outro colaborador' USING ERRCODE='42501'; END IF;
 SELECT * INTO v_claim FROM public.research_participation_badges
  WHERE answer_id=v_answer.id OR (user_id=auth.uid() AND form_id=v_answer.form_id)
  FOR UPDATE;
 IF FOUND THEN
   IF v_claim.user_id<>auth.uid() THEN
     RAISE EXCEPTION 'Este recibo já foi vinculado a outra conta' USING ERRCODE='23505';
   END IF;
   RETURN jsonb_build_object('status','already_linked','form_id',v_claim.form_id);
 END IF;
 INSERT INTO public.research_participation_badges(user_id,form_id,answer_id)
 VALUES(auth.uid(),v_answer.form_id,v_answer.id)
 ON CONFLICT DO NOTHING
 RETURNING * INTO v_claim;
 IF NOT FOUND THEN
   RAISE EXCEPTION 'Recibo já vinculado ou vínculo duplicado' USING ERRCODE='23505';
 END IF;
 RETURN jsonb_build_object('status','linked','form_id',v_claim.form_id);
END $$;

-- Combined BI preserves every category introduced by 0097 and 0098.
CREATE OR REPLACE FUNCTION public.get_configured_research_summary(p_filters jsonb DEFAULT '{}')
RETURNS TABLE(version_id uuid,version_number integer,semantic_code text,category text,eligible bigint,answered bigint,total bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF auth.uid() IS NULL OR NOT public.has_role(auth.uid(),'admin') THEN RAISE EXCEPTION 'Admin only' USING ERRCODE='42501'; END IF;
 RETURN QUERY
 WITH base AS (
  SELECT a.id,a.version_id,a.answers,v.schema_json,j.journey,j.configuration_snapshot AS c
  FROM public.research_answers a JOIN public.research_journeys j ON j.answer_id=a.id
  JOIN public.research_form_versions v ON v.id=a.version_id AND v.form_id=a.form_id
  WHERE (p_filters->>'formId' IS NULL OR a.form_id=(p_filters->>'formId')::uuid)
   AND (p_filters->>'versionId' IS NULL OR a.version_id=(p_filters->>'versionId')::uuid)
   AND (p_filters->>'periodStart' IS NULL OR a.submitted_at>=(p_filters->>'periodStart')::timestamptz)
   AND (p_filters->>'periodEnd' IS NULL OR a.submitted_at<(p_filters->>'periodEnd')::timestamptz)
   AND NOT EXISTS(SELECT 1 FROM jsonb_each_text(p_filters) f WHERE
    (f.key IN ('institutionId','campus','campaignType','templateKey','region','acquisitionSource','nearbyUniversity') AND j.configuration_snapshot->>f.key IS DISTINCT FROM f.value)
    OR (f.key IN ('profile','mode') AND j.journey->>f.key IS DISTINCT FROM f.value)
    OR (f.key='time' AND j.journey->>'outboundTime' IS DISTINCT FROM f.value))
 ), questions AS (
  SELECT b.id,b.version_id,b.answers,q.value AS q FROM base b
  CROSS JOIN LATERAL jsonb_array_elements(b.schema_json->'sections') s
  CROSS JOIN LATERAL jsonb_array_elements(s->'questions') q
  WHERE q.value->>'type' IN ('single_choice','multiple_choice','yes_no','rating_1_5','rating_0_10','rating_stars','money_range','number','time')
   AND q.value->>'semanticCode' IN ('TRANSPORT_MODE','COST_PER_TRIP','TRAVEL_TIME','WAIT_TIME','ACADEMIC_ROLE','SEATS_AVAILABLE','MOBILITY_PAINS','PERCEIVED_SAFETY','ADOPTION_INTENT','TRUST_FACTORS',
    'RIDE_OFFER_INTENT','BOOKING_INTENT','MOBILITY_MODE','NORMALIZED_DEPARTURE_TIME','TRAVEL_FREQUENCY','ACCEPTABLE_FARE_RANGE','WILLINGNESS_TO_PAY','QUOTE_ACCEPTANCE_INTENT','ACQUISITION_SOURCE','LAUNCH_PARTICIPATION_INTENT',
    'REGIONAL_SERVICE_PREFERENCE','REGIONAL_PRIMARY_PAIN','REGIONAL_BARRIER','REGIONAL_OFFER_POSSIBLE',
    'REGIONAL_OFFER_VEHICLE','REGIONAL_PROFESSIONAL_ROLE','REGIONAL_PROFESSIONAL_INTEREST',
    'COMPANY_DRIVES_CAR','COMPANY_DRIVING_FREQUENCY','COMPANY_MAX_DETOUR','CORP_DRIVES_CAR','WORK_SHIFT')
   AND (q.value->'showWhen' IS NULL OR q.value->'showWhen'='null'::jsonb OR b.answers->>(q.value#>>'{showWhen,questionId}')=q.value#>>'{showWhen,equals}')
 ), denominators AS (
  SELECT q.version_id,q.q->>'semanticCode' AS code,count(DISTINCT q.id) AS eligible,
   count(DISTINCT q.id) FILTER(WHERE q.answers ? (q.q->>'id') AND q.answers->(q.q->>'id') NOT IN ('null'::jsonb,'""'::jsonb,'[]'::jsonb)) AS answered
  FROM questions q GROUP BY q.version_id,q.q->>'semanticCode'
 ), values_flat AS (
  SELECT q.version_id,q.q->>'semanticCode' AS code,val.value AS category,count(DISTINCT q.id) AS total FROM questions q
  CROSS JOIN LATERAL jsonb_array_elements_text(CASE WHEN jsonb_typeof(q.answers->(q.q->>'id'))='array' THEN q.answers->(q.q->>'id') ELSE jsonb_build_array(q.answers->(q.q->>'id')) END) val
  WHERE val.value IS NOT NULL AND val.value<>'' GROUP BY q.version_id,q.q->>'semanticCode',val.value
 )
 , journey_values AS (
  SELECT b.version_id,x.code,x.category,count(DISTINCT b.id) AS total FROM base b
  CROSS JOIN LATERAL (VALUES('JOURNEY_PROFILE',b.journey->>'profile'),('JOURNEY_MODE',b.journey->>'mode'),('JOURNEY_DEPARTURE_TIME',b.journey->>'outboundTime')) x(code,category)
  GROUP BY b.version_id,x.code,x.category
 ), interests AS (
  SELECT b.version_id,CASE WHEN i.profile='PASSAGEIRO' THEN 'PASSENGER_INTEREST_REGISTERED' ELSE 'DRIVER_AVAILABILITY_REGISTERED' END AS code,
   i.status AS category,count(DISTINCT b.id) AS total FROM base b JOIN public.research_interest_requests i ON i.answer_id=b.id GROUP BY b.version_id,i.profile,i.status
 ), combined AS (
  SELECT d.version_id,d.code,v.category,d.eligible,d.answered,coalesce(v.total,0) AS total FROM denominators d LEFT JOIN values_flat v ON v.version_id=d.version_id AND v.code=d.code
  UNION ALL
  SELECT x.version_id,x.code,x.category,(SELECT count(*) FROM base b WHERE b.version_id=x.version_id),
   (SELECT count(*) FROM base b WHERE b.version_id=x.version_id),x.total FROM journey_values x
  UNION ALL
  SELECT i.version_id,i.code,i.category,(SELECT count(*) FROM base b WHERE b.version_id=i.version_id AND b.journey->>'profile' IN (CASE WHEN i.code='PASSENGER_INTEREST_REGISTERED' THEN 'PASSAGEIRO' ELSE 'MOTORISTA' END,'AMBOS')),
   i.total,i.total FROM interests i
 )
 SELECT c.version_id,v.version_number,c.code,c.category,c.eligible,c.answered,c.total FROM combined c JOIN public.research_form_versions v ON v.id=c.version_id;
END $$;
REVOKE ALL ON FUNCTION public.get_configured_research_summary(jsonb) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.get_configured_research_summary(jsonb) TO authenticated;




